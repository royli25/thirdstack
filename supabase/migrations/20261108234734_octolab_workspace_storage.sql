CREATE FUNCTION json_extract(document TEXT,path TEXT) RETURNS TEXT LANGUAGE SQL IMMUTABLE STRICT PARALLEL SAFE AS $$ SELECT document::jsonb #>> string_to_array(substr(path,3),'.') $$;
CREATE FUNCTION json_each(document TEXT,path TEXT) RETURNS TABLE(key TEXT,value TEXT) LANGUAGE SQL IMMUTABLE STRICT PARALLEL SAFE AS $$ SELECT (ordinality-1)::text,value::text FROM jsonb_array_elements(document::jsonb #> string_to_array(substr(path,3),'.')) WITH ORDINALITY $$;

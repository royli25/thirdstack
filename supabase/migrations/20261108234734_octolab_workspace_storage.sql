-- Private backend schema: browser roles have no direct access.
CREATE SCHEMA IF NOT EXISTS octolab;
REVOKE ALL ON SCHEMA octolab FROM PUBLIC;
DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='octolab_runtime') THEN CREATE ROLE octolab_runtime NOLOGIN NOBYPASSRLS; END IF; END $$;
GRANT octolab_runtime TO CURRENT_USER;
SET search_path TO octolab, pg_catalog;
CREATE TABLE workspaces(id TEXT PRIMARY KEY, name TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE workspace_memberships(workspace_id TEXT NOT NULL REFERENCES workspaces(id),user_id UUID NOT NULL,role TEXT NOT NULL CHECK(role IN ('owner','member')),PRIMARY KEY(workspace_id,user_id));
CREATE INDEX memberships_user ON workspace_memberships(user_id);
CREATE TABLE migration_imports(workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),source_digest TEXT NOT NULL,counts JSONB NOT NULL,imported_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE tasks(
  id TEXT NOT NULL,
  body TEXT NOT NULL,
  workspace_id TEXT NOT NULL DEFAULT current_setting('octolab.workspace_id'),
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY(workspace_id,id)
);
CREATE TABLE events(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  task_id TEXT NOT NULL,
  call_id TEXT,
  type TEXT NOT NULL,
  at TEXT NOT NULL,
  data TEXT NOT NULL,
  workspace_id TEXT NOT NULL DEFAULT current_setting('octolab.workspace_id'),
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY(workspace_id,id),
  FOREIGN KEY(workspace_id,task_id) REFERENCES tasks(workspace_id,id) ON DELETE CASCADE
);
CREATE INDEX events_task ON events(workspace_id,task_id,id);
CREATE TABLE request_receipts(
  task_id TEXT NOT NULL,
  operation TEXT NOT NULL,
  request_key TEXT NOT NULL,
  args_hash TEXT NOT NULL,
  state TEXT NOT NULL,
  http_status INTEGER NOT NULL,
  body TEXT NOT NULL,
  PRIMARY KEY(workspace_id,task_id,operation,request_key),
  workspace_id TEXT NOT NULL DEFAULT current_setting('octolab.workspace_id'),
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
  FOREIGN KEY(workspace_id,task_id) REFERENCES tasks(workspace_id,id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX event_ledger_once ON events(workspace_id,call_id,type) WHERE call_id IS NOT NULL AND type IN ('budget_reserved','budget_settled','provider_request','provider_response');
CREATE TABLE observation_clients(
  id TEXT NOT NULL,
  body TEXT NOT NULL,
  workspace_id TEXT NOT NULL DEFAULT current_setting('octolab.workspace_id'),
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,

-- Immutable provider diagnostics belong to the same private workspace as their runs.
CREATE TABLE octolab.provider_lab_suites (
  id TEXT NOT NULL,
  revision INTEGER NOT NULL CHECK (revision > 0),
  body TEXT NOT NULL,
  workspace_id TEXT NOT NULL DEFAULT current_setting('octolab.workspace_id'),
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY (workspace_id, id, revision)
);
ALTER TABLE octolab.provider_lab_suites ENABLE ROW LEVEL SECURITY;
ALTER TABLE octolab.provider_lab_suites FORCE ROW LEVEL SECURITY;
CREATE POLICY workspace_scope ON octolab.provider_lab_suites TO octolab_runtime
  USING (workspace_id = current_setting('octolab.workspace_id', true))
  WITH CHECK (workspace_id = current_setting('octolab.workspace_id', true));
GRANT SELECT, INSERT, UPDATE, DELETE ON octolab.provider_lab_suites TO octolab_runtime;
GRANT USAGE, SELECT ON SEQUENCE octolab.provider_lab_suites_rowid_seq TO octolab_runtime;
CREATE INDEX provider_lab_suites_workspace_order ON octolab.provider_lab_suites(workspace_id, rowid);
